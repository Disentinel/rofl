// scripts/merge_train.ts — THE MERGE TRAIN, a merge queue for a repository that has none (.github/workflows/merge-train.yml).
//
// A pull request labelled `queue` waits for the train, which takes it once its fast checks are green on its head; a red
// head is said on it once and it keeps its label, so a fix pushed to the branch is taken without labelling again. The train takes
// every such request, stacks each on main as its squash would land, regenerates the files the tree generates (their
// conflicts are taken from the stack and made again), blesses the goldens once, and asks
// models/process/ci/train.rofl whether a world answers otherwise than the one party that moved it. Then the slow gates
// run once over the stack, and each request lands in turn by GitHub's own squash merge of a commit whose tree is the
// stack's: linear history, every request marked merged. A red train of several is taken again one request at a time
// (label `train-red`); a red train of one returns its request with the reason.
//
//   node --experimental-strip-types scripts/merge_train.ts pick            the requests the train takes, as JSON
//   node --experimental-strip-types scripts/merge_train.ts stack           stack them on HEAD (main); conflicts returned
//   node --experimental-strip-types scripts/merge_train.ts regenerate      the generated files, the goldens last
//   node --experimental-strip-types scripts/merge_train.ts judge           train.rofl over the goldens of every side
//   node --experimental-strip-types scripts/merge_train.ts features        what each request did, by feature, for land to say
//   node --experimental-strip-types scripts/merge_train.ts land            each request merged in turn
//   node --experimental-strip-types scripts/merge_train.ts fail            the train is red: say so on its requests
//   node --experimental-strip-types scripts/merge_train.ts rerun RUN       a run lost to its machine, run again once
//
// GITHUB_TOKEN and GITHUB_REPOSITORY from Actions; the state between steps is .cache/train/state.json.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { execFileSync } from 'node:child_process';
import { Rofl } from '../src/api.ts';
import { parse } from './goldens.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const STATE = path.join(ROOT, '.cache/train/state.json');
const REPO = process.env.GITHUB_REPOSITORY ?? 'Disentinel/rofl';
const RUN_URL = process.env.GITHUB_RUN_ID ? `https://github.com/${REPO}/actions/runs/${process.env.GITHUB_RUN_ID}` : '';
const QUEUE = 'queue', RED = 'train-red';
// the jobs of ci.yml a pull request must have green on its head before the train takes it
const FAST = ['model', 'clippy', 'node'];
// generated files: on a conflict the stack's side is kept and the file made again, in this order, the goldens last
const MADE: [string, string[]][] = [
  ['examples/checks/agg-breaks-census.rofl', ['node', '--experimental-strip-types', 'scripts/agg_breaks.ts', '--census', '--write']],
  ['facts/spec-census.rofl', ['npm', 'run', 'speccheck', '--', '--write']],
  ['facts/goldens.rofl', ['npm', 'run', 'bless']],
];

type Pr = { number: number; title: string; ref: string; head: string; base: string; labels: string[] };
type Stacked = Pr & { commit: string };
type State = { main: string; solo: boolean; stacked: Stacked[]; returned: { pr: Pr; files: string[] }[] };

// every commit the train makes is the train's, whatever the machine's git knows
Object.assign(process.env, { GIT_AUTHOR_NAME: 'merge-train', GIT_AUTHOR_EMAIL: 'merge-train@users.noreply.github.com', GIT_COMMITTER_NAME: 'merge-train', GIT_COMMITTER_EMAIL: 'merge-train@users.noreply.github.com' });
const git = (...args: string[]): string => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28 }).trim();
const gitOk = (...args: string[]): boolean => { try { git(...args); return true; } catch { return false; } };

async function gh<T>(method: string, url: string, body?: unknown): Promise<T> {
  const r = await fetch(`https://api.github.com/repos/${REPO}${url}`, {
    method,
    headers: { authorization: `Bearer ${process.env.GITHUB_TOKEN}`, accept: 'application/vnd.github+json', 'x-github-api-version': '2022-11-28' },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!r.ok) throw new Error(`${method} ${url}: ${r.status} ${await r.text()}`);
  return (r.status === 204 ? undefined : await r.json()) as T;
}
const say = (n: number, text: string): Promise<unknown> =>
  gh('POST', `/issues/${n}/comments`, { body: `${text}${RUN_URL ? `\n\n[the train's run](${RUN_URL})` : ''}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_` });
const unlabel = (n: number, l: string): Promise<unknown> => gh('DELETE', `/issues/${n}/labels/${l}`).catch(() => undefined);
const RED_HEAD = 'The train waits: red on';
const saidRed = async (n: number, sha: string): Promise<boolean> =>
  (await gh<{ body: string }[]>('GET', `/issues/${n}/comments?per_page=100`)).some((c) => c.body.startsWith(`${RED_HEAD} ${sha}`));
const read = (): State => JSON.parse(fs.readFileSync(STATE, 'utf8')) as State;
const write = (s: State): void => { fs.mkdirSync(path.dirname(STATE), { recursive: true }); fs.writeFileSync(STATE, JSON.stringify(s, null, 2)); };

/** The open requests labelled `queue` whose fast checks are green on their head, oldest first; one alone after a red
 *  train of several. */
async function pick(): Promise<void> {
  const open = await gh<any[]>('GET', '/pulls?state=open&base=main&per_page=100&sort=created&direction=asc');
  const ready: Pr[] = [];
  for (const p of open) {
    const labels = (p.labels as { name: string }[]).map((l) => l.name);
    if (p.draft || !labels.includes(QUEUE)) continue;
    const runs = (await gh<{ check_runs: { name: string; conclusion: string | null }[] }>('GET', `/commits/${p.head.sha}/check-runs?per_page=100`)).check_runs;
    const red = FAST.filter((j) => !runs.some((r) => r.name === j && r.conclusion === 'success'));
    if (red.length) {
      // a request that conflicts with main gets no run of ci.yml at all, and would wait for ever (#274)
      if ((await gh<{ mergeable: boolean | null }>('GET', `/pulls/${p.number}`)).mergeable === false) {
        await returnPr({ number: p.number } as Pr, 'This conflicts with main, so GitHub runs no CI on it and the train cannot take it. Merge main and label it `queue` again.');
        console.error(`#${p.number} returned: it conflicts with main`);
      } else {
        const sha = p.head.sha.slice(0, 7);
        const failed = red.filter((j) => runs.some((r) => r.name === j && (r.conclusion === 'failure' || r.conclusion === 'timed_out')));
        if (failed.length && !(await saidRed(p.number, sha))) await say(p.number, `${RED_HEAD} ${sha}: ${failed.join(', ')}. The train waits for a green head of this branch; push the fix, the label stays.`);
        console.error(`#${p.number} waits: ${red.join(', ')} not green on ${sha}`);
      }
      continue;
    }
    ready.push({ number: p.number, title: p.title, ref: p.head.ref, head: p.head.sha, base: '', labels });
  }
  const solo = ready.some((p) => p.labels.includes(RED));
  const take = solo ? ready.slice(0, 1) : ready;
  write({ main: '', solo, stacked: [], returned: [] });
  fs.writeFileSync(path.join(path.dirname(STATE), 'picked.json'), JSON.stringify(take));
  console.log(take.length ? `the train takes ${take.map((p) => `#${p.number}`).join(' ')}${solo ? ' (alone, after a red train)' : ''}` : 'nothing waits');
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `count=${take.length}\n`);
}

/** Each request squashed onto the stack in turn. The ledgers merge by line (.gitattributes, merge=union); a generated
 *  file keeps the stack's side and is made again later; any other conflict returns the request. */
function stack(): void {
  const s = read(), take = JSON.parse(fs.readFileSync(path.join(path.dirname(STATE), 'picked.json'), 'utf8')) as Pr[];
  s.main = git('rev-parse', 'HEAD');
  const made = new Set(MADE.map(([f]) => f));
  for (const p of take) {
    git('fetch', '-q', 'origin', `${p.head}`);
    p.base = git('merge-base', s.main, p.head);
    if (!gitOk('merge', '--squash', '--no-commit', p.head)) {
      const files = git('diff', '--name-only', '--diff-filter=U').split('\n').filter(Boolean);
      if (!files.length) throw new Error(`#${p.number}: git merge failed with no conflict: the train is broken, not the request`);
      for (const f of files.filter((f) => made.has(f))) { git('checkout', '--ours', '--', f); git('add', '--', f); }
      const left = files.filter((f) => !made.has(f));
      if (left.length) { git('reset', '-q', '--hard', 'HEAD'); s.returned.push({ pr: p, files: left }); console.log(`#${p.number} returned: ${left.join(', ')}`); continue; }
    }
    if (gitOk('diff', '--cached', '--quiet') && !gitOk('diff', '--quiet', p.base, p.head))
      throw new Error(`#${p.number} changes the tree and its squash on the stack changes nothing: the train is broken, not the request`);
    git('commit', '-q', '--allow-empty', '-m', `${p.title} (#${p.number})`);
    s.stacked.push({ ...p, commit: git('rev-parse', 'HEAD') });
    console.log(`#${p.number} stacked`);
  }
  write(s);
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `stacked=${s.stacked.length}\n`);
}

/** The generated files made again over the whole stack, folded into its last commit. */
function regenerate(): void {
  const s = read();
  if (!s.stacked.length) return;
  for (const [f, cmd] of MADE) {
    console.log(`::group::${f}`);
    execFileSync(cmd[0], cmd.slice(1), { cwd: ROOT, stdio: 'inherit', env: { ...process.env } });
    console.log('::endgroup::');
  }
  git('add', '--', ...MADE.map(([f]) => f));
  git('commit', '-q', '--amend', '--no-edit', '--allow-empty');
  s.stacked[s.stacked.length - 1].commit = git('rev-parse', 'HEAD');
  write(s);
}

/** train.rofl over golden(Side, P, World, Hash): main, each request's base and blessing, the stack's. */
function judge(): number {
  const s = read();
  const sides: [string, string, string | null][] = [['main', '', s.main], ['new', '', null]];
  for (const p of s.stacked) sides.push(['pr', `#${p.number}`, p.head], ['base', `#${p.number}`, p.base]);
  const at = sides.map(([side, pr, ref]) => [side, pr, parse(ref === null ? undefined : git('show', `${ref}:facts/goldens.rofl`))] as const);
  const names = new Set(at.flatMap(([, , g]) => [...g.keys()]));
  const q = (x: string): string => JSON.stringify(x);
  const facts = at.flatMap(([side, pr, g]) => [...names].map((w) => `golden(${q(side)}, ${q(pr)}, ${q(w)}, ${q(g.get(w)?.hash ?? '-')}).`));
  const r = new Rofl();
  r.load(fs.readFileSync(path.join(ROOT, 'boot.rofl'), 'utf8'));
  for (const text of [fs.readFileSync(path.join(ROOT, 'models/process/ci/train.rofl'), 'utf8'), facts.join('\n')]) {
    const res = r.load(text);
    if (!res.ok) throw new Error(`train.rofl does not load: ${res.diagnostics[0]}`);
  }
  r.evaluate();
  const rows = (query: string, ...vs: string[]): string[][] =>
    r.query(query).rows.map((x) => vs.map((v) => { const t = String(x.bindings[v]); return t.startsWith('"') ? JSON.parse(t) as string : t; })).sort();
  for (const [w] of rows('reblessed(W)', 'W')) console.log(`blessed by the train: ${w} (moved by more than one party)`);
  const met = rows('met(W, G, E)', 'W', 'G', 'E');
  for (const [w, got, want] of met) console.log(`MET ${w}: the stack answers ${got}, the one party that moved it blessed ${want}`);
  fs.writeFileSync(path.join(path.dirname(STATE), 'met.txt'), met.map(([w]) => w).join(', '));
  console.log(met.length ? `${met.length} worlds where two changes meet: the train stops` : 'every golden is its party\'s');
  return met.length ? 1 : 0;
}

/** What each request of the stack did, said by feature: scripts/features.sh over the stack's commits, asked through
 *  models/engine/feature-behaviour.rofl; one comment per request in .cache/train/features/, said on it when it lands. */
function features(): void {
  const s = read();
  if (!s.stacked.length) return;
  execFileSync('sh', ['scripts/features.sh', String(s.stacked.length), 'HEAD'], { cwd: ROOT, stdio: 'inherit' });
  const asks = ['verdict(P, K, N, V)', 'points_most(P, K, N)', 'by(P, W, M, C)', 'dearer(P, W, M, X, Y)', 'cheaper(P, W, M, X, Y)'];
  const out = execFileSync('rust/target/release/rofl', ['load', '--json', ...asks.flatMap((a) => ['--ask', a]), 'boot.rofl',
    'models/engine/feature-diff.rofl', 'models/engine/feature-behaviour.rofl', '.cache/engine/features/world.rofl'],
  { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28 });
  const rows = new Map<string, string[][]>();
  for (const line of out.split('\n').filter(Boolean)) {
    const a = JSON.parse(line) as { ok: boolean; keys: string[]; error?: string };
    if (!a.ok) throw new Error(`feature-behaviour.rofl: ${a.error}`);
    for (const k of a.keys) {
      const m = /^(\w+)\[\w+\]\((.*)\)$/.exec(k)!;
      const args = (m[2].match(/"(?:[^"\\]|\\.)*"|[^,\s]+/g) ?? []).map((x) => x.startsWith('"') ? JSON.parse(x) as string : x);
      rows.set(m[1], [...rows.get(m[1]) ?? [], args]);
    }
  }
  const of = (rel: string, n: number): string[][] => (rows.get(rel) ?? []).filter((r) => r[0] === String(n)).map((r) => r.slice(1)).sort();
  const means = { changed: 'its code written and its worlds answer otherwise', held: 'its code written, its worlds answer as before',
    unwatched: 'its code written, and no world says it', carried: 'its code not written, and its worlds answer otherwise' };
  const dir = path.join(path.dirname(STATE), 'features');
  fs.mkdirSync(dir, { recursive: true });
  for (const p of s.stacked) {
    const lines = ['**What this change did, by feature** (models/engine/feature-behaviour.rofl over the train\'s stack)', ''];
    for (const [v, why] of Object.entries(means)) {
      const names = of('verdict', p.number).filter((r) => r[2] === v).map(([k, n]) => `${k} \`${n}\``);
      if (names.length) lines.push(`- **${v}** (${why}): ${names.join(', ')}`);
    }
    const most = of('points_most', p.number).map(([k, n]) => `${k} \`${n}\``);
    if (most.length) lines.push(`- the moved worlds point at: ${most.join(', ')}`);
    const engine = of('by', p.number).filter((r) => r[1] === 'answer' && r[2] === 'engine').map((r) => r[0]);
    if (engine.length) lines.push(`- worlds whose answer the engine alone moved: ${engine.length} (${engine.slice(0, 12).map((w) => `\`${w}\``).join(', ')}${engine.length > 12 ? ', ...' : ''})`);
    const own = of('by', p.number).filter((r) => r[1] === 'answer' && r[2] !== 'engine').map((r) => r[0]);
    if (own.length) lines.push(`- worlds whose answer moved with their own files: ${own.length} (${own.slice(0, 12).map((w) => `\`${w}\``).join(', ')}${own.length > 12 ? ', ...' : ''})`);
    for (const [rel, word] of [['dearer', 'dearer'], ['cheaper', 'cheaper']] as const) {
      const ws = of(rel, p.number).map(([w, m, x, y]) => `\`${w}\` ${m === 'space' ? 'peak rows' : m} ${x} → ${y}`);
      if (ws.length) lines.push(`- ${word} by the engine alone: ${ws.slice(0, 12).join('; ')}${ws.length > 12 ? `; and ${ws.length - 12} more` : ''}`);
    }
    if (!of('verdict', p.number).length && !engine.length) lines.push('- no entry of the engine written, and no world the engine moved');
    fs.writeFileSync(path.join(dir, `${p.number}.md`), lines.join('\n'));
    console.log(`#${p.number}\n${lines.slice(2).join('\n')}`);
  }
}

/** Each request in turn: a commit whose parents are its head and main as it now is and whose tree is the stack's after
 *  it, pushed to its branch (a fast-forward), then GitHub's squash of it: main becomes that tree. */
async function land(): Promise<void> {
  const s = read();
  let main = (await gh<{ object: { sha: string } }>('GET', '/git/ref/heads/main')).object.sha;
  if (main !== s.main) return void console.log(`main moved while the train ran (${s.main.slice(0, 7)} -> ${main.slice(0, 7)}), not by the train: the next train takes these`);
  let landed = 0;
  for (const p of s.stacked) {
    const tree = git('rev-parse', `${p.commit}^{tree}`);
    git('fetch', '-q', 'origin', main);
    const m = git('commit-tree', tree, '-p', p.head, '-p', main, '-m', `The merge train: main and the train before #${p.number} merged in`);
    // each later request's tree holds this one's change: a request that does not land stops the landing there
    const stop = async (why: string): Promise<void> => {
      await returnPr(p, why);
      for (const q of s.stacked.slice(landed + 1)) await unlabel(q.number, RED);
      console.log(`#${p.number} not landed: ${why} The rest wait for the next train.`);
    };
    // what the request is now, not what it was when the train took it: an hour of gates lies between
    const now = await gh<{ head: { sha: string }; labels: { name: string }[] }>('GET', `/pulls/${p.number}`);
    if (!now.labels.some((l) => l.name === QUEUE)) { await stop('the label `queue` was taken off while the train ran, so it does not land; label it again to send it.'); break; }
    if (now.head.sha !== p.head) { await stop(`its branch moved to ${now.head.sha.slice(0, 7)} since the train took ${p.head.slice(0, 7)}; the next train takes the new head.`); break; }
    if (!gitOk('push', '-q', 'origin', `${m}:refs/heads/${p.ref}`)) { await stop('its branch moved since the train took it; label it `queue` again.'); break; }
    const sha = await squash(p, m);
    if (!sha) { await stop('GitHub would not squash it after the train merged main into its branch; label it `queue` again.'); break; }
    main = sha; landed++;
    await unlabel(p.number, QUEUE); await unlabel(p.number, RED);
    const report = path.join(path.dirname(STATE), 'features', `${p.number}.md`);
    if (fs.existsSync(report)) await say(p.number, fs.readFileSync(report, 'utf8')).catch((e) => console.log(`#${p.number}: ${(e as Error).message.slice(0, 200)}`));
    console.log(`#${p.number} landed as ${main.slice(0, 7)}`);
  }
  for (const { pr, files } of s.returned) await returnPr(pr, `The train could not stack this on main: ${files.map((f) => `\`${f}\``).join(', ')} conflict. Rebase on main and label it \`queue\` again.`);
  // a push by the workflow's own token starts no workflow: main's run (engine, vsix, release rehearsal) is asked for
  if (landed) await gh('POST', '/actions/workflows/ci.yml/dispatches', { ref: 'main' });
}

/** GitHub's squash of a request whose branch was just pushed: it says whether the request merges only once it has
 *  computed it, so the merge waits for that and is tried again while GitHub still says no. */
async function squash(p: Pr, m: string): Promise<string | null> {
  for (let i = 0; i < 12; i++) {
    const pr = await gh<{ head: { sha: string }; mergeable: boolean | null }>('GET', `/pulls/${p.number}`);
    if (pr.head.sha === m && pr.mergeable) {
      try { return (await gh<{ sha: string }>('PUT', `/pulls/${p.number}/merge`, { merge_method: 'squash', sha: m, commit_title: `${p.title} (#${p.number})` })).sha; }
      catch (e) { console.log(`#${p.number}: ${(e as Error).message.slice(0, 200)}`); }
    }
    await new Promise((r) => setTimeout(r, 5000));
  }
  return null;
}

async function returnPr(p: Pr, why: string): Promise<void> {
  await unlabel(p.number, QUEUE); await unlabel(p.number, RED);
  await say(p.number, why);
}

/** A red train: of several, each is taken again alone; of one, it goes back to its author. */
async function fail(): Promise<void> {
  const s = read(), metFile = path.join(path.dirname(STATE), 'met.txt');
  const met = fs.existsSync(metFile) ? fs.readFileSync(metFile, 'utf8') : '';
  const reason = met ? `two changes meet in ${met}: each answers otherwise than the one change that moved it blessed (models/process/ci/train.rofl)` : 'a gate of the train is red';
  if (s.stacked.length > 1) for (const p of s.stacked) await gh('POST', `/issues/${p.number}/labels`, { labels: [RED] });
  else for (const p of s.stacked) await returnPr(p, `The train is red on this alone: ${reason}`);
  for (const { pr, files } of s.returned) await returnPr(pr, `The train could not stack this on main: ${files.map((f) => `\`${f}\``).join(', ')} conflict. Rebase on main and label it \`queue\` again.`);
}

/** A run whose jobs were cancelled while its commit is still the head of its branch was not superseded: its machine
 *  went away. Run its failed and cancelled jobs again, once. */
async function rerun(id: string): Promise<void> {
  const run = await gh<any>('GET', `/actions/runs/${id}`);
  if (run.run_attempt > 1 || run.conclusion === 'success') return void console.log(`run ${id}: attempt ${run.run_attempt}, ${run.conclusion}: left`);
  const jobs = (await gh<{ jobs: { name: string; conclusion: string }[] }>('GET', `/actions/runs/${id}/jobs?per_page=100`)).jobs;
  const lost = jobs.filter((j) => j.conclusion === 'cancelled');
  if (!lost.length) return void console.log(`run ${id}: nothing cancelled, a verdict: left`);
  const head = run.event === 'pull_request' && run.pull_requests?.[0]
    ? (await gh<any>('GET', `/pulls/${run.pull_requests[0].number}`)).head.sha
    : (await gh<{ object: { sha: string } }>('GET', `/git/ref/heads/${run.head_branch}`).catch(() => ({ object: { sha: '' } }))).object.sha;
  if (head !== run.head_sha) return void console.log(`run ${id}: superseded by ${head.slice(0, 7)}: left`);
  await gh('POST', `/actions/runs/${id}/rerun-failed-jobs`);
  console.log(`run ${id}: ${lost.map((j) => j.name).join(', ')} cancelled on the head of ${run.head_branch}: run again`);
}

const [cmd, arg] = process.argv.slice(2);
const steps: Record<string, () => unknown> = {
  pick, stack, regenerate, features, land, judge: () => { process.exitCode = judge(); },
  fail, rerun: () => rerun(arg),
};
if (!steps[cmd]) { console.error(`merge_train: ${Object.keys(steps).join(' | ')}`); process.exit(2); }
await steps[cmd]();
