//! THE OPENAPI ADAPTER (docs/intents.md 7, scenario 6): an HTTP service described by an OpenAPI document.
//!
//! `book` is `rofl adapter openapi SPEC`: the document (JSON, a file or a URL) printed as an adapter book, a block
//! per operation, sorted by capability, so a book regenerated after one operation changed differs by that block alone.
//! GET and HEAD are `reads`, every other method `does` (D2), until a person changes the line. An operation's
//! parameters and the properties of its JSON body are its arguments, in that order, each placed by
//! `http_in(Cap, Pos, path|query|header|body, Name)`; its first 2xx JSON answer, an object or an array of objects,
//! answers a column a property (`http_field(Cap, Pos, Name)`), any other answer its text in `http_body(K, Text)`.
//!
//! Credentials (`components.securitySchemes`) are named, never held: `http_auth(Adapter, Scheme, How, Name, Env)` says
//! the environment variable that holds the key and where it goes (`bearer`, `basic`, a `header` or the `query`), and
//! `http_needs(Cap, Scheme)` which an operation needs. A want whose key the environment does not give is
//! `want_held` (declared, not connected), and a key never enters a fact.
//!
//! `call` is the `openapi` kind: one request per want, an array answering a row per element, a status that is not
//! 2xx `failed(K, "HTTP N: ...")`. A `does` want carries its idempotency key in the `Idempotency-Key` header.
use crate::mcp::{fact_value, ident, quote};
use serde_json::Value;

/// The adapter book of the document at `spec`.
pub fn book(spec: &str) -> Result<String, String> {
    let text = if spec.starts_with("http://") || spec.starts_with("https://") {
        let r = crate::net::send("GET", spec, &[], None)?;
        if r.status / 100 != 2 {
            return Err(format!("{spec}: HTTP {}", r.status));
        }
        r.body
    } else {
        std::fs::read_to_string(spec).map_err(|e| format!("{spec}: {e}"))?
    };
    let doc: Value = match serde_json::from_str(&text) {
        Ok(d) => d,
        Err(_) => serde_yaml::from_str(&text).map_err(|e| format!("{spec}: neither JSON nor YAML: {e}"))?,
    };
    let adapter = ident(doc.pointer("/info/title").and_then(Value::as_str).unwrap_or("api"));
    let base = doc.pointer("/servers/0/url").and_then(Value::as_str).unwrap_or("http://localhost");
    let mut blocks = Vec::new();
    for (path, item) in doc.get("paths").and_then(Value::as_object).into_iter().flatten() {
        let shared = item.get("parameters").and_then(Value::as_array).cloned().unwrap_or_default();
        for method in ["get", "head", "post", "put", "patch", "delete"] {
            if let Some(op) = item.get(method) {
                blocks.push(op_block(&doc, &adapter, method, path, op, &shared));
            }
        }
    }
    blocks.sort();
    let mut out = format!(
        "-- generated by `rofl adapter openapi` from {spec}; GET and HEAD are `reads`, every other method `does` until a person changes its line\nadapter({adapter}, openapi, {}).\n",
        quote(base)
    );
    let schemes = doc.pointer("/components/securitySchemes").and_then(Value::as_object);
    for (n, s) in schemes.into_iter().flatten() {
        let s = resolve(&doc, s);
        let (how, name) = match (s.get("type").and_then(Value::as_str), s.get("scheme").and_then(Value::as_str), s.get("in").and_then(Value::as_str)) {
            (Some("apiKey"), _, Some(at @ ("header" | "query"))) => (at, s.get("name").and_then(Value::as_str).unwrap_or(n.as_str())),
            (Some("http"), Some(b), _) if b.eq_ignore_ascii_case("basic") => ("basic", "Authorization"),
            (Some("http" | "oauth2" | "openIdConnect"), _, _) => ("bearer", "Authorization"),
            _ => continue,
        };
        let env = format!("{adapter}_{}", ident(n)).to_uppercase();
        out.push_str(&format!("http_auth({adapter}, {}, {how}, {}, {}).\n", ident(n), quote(name), quote(&env)));
    }
    if crate::brk!("openapi_book_digest" => true; false) {
        out.push_str(&format!("-- document {:016x}\n", text.bytes().fold(0xcbf29ce484222325u64, |h, b| (h ^ b as u64).wrapping_mul(0x100000001b3))));
    }
    for (_, b) in blocks {
        out.push('\n');
        out.push_str(&b);
    }
    Ok(out)
}

/// The schema `v` names, `$ref`s within the document followed.
fn resolve<'a>(doc: &'a Value, v: &'a Value) -> &'a Value {
    let mut v = v;
    for _ in 0..16 {
        match v.get("$ref").and_then(Value::as_str).and_then(|r| r.strip_prefix('#')) {
            Some(p) => v = doc.pointer(p).unwrap_or(&Value::Null),
            None => break,
        }
    }
    v
}

fn ty(doc: &Value, schema: &Value) -> &'static str {
    match resolve(doc, schema).get("type").and_then(Value::as_str) {
        Some("string") => "text",
        Some("integer" | "number") => "number",
        Some("boolean") => "atom",
        _ => "json",
    }
}

fn op_block(doc: &Value, adapter: &str, method: &str, path: &str, op: &Value, shared: &[Value]) -> (String, String) {
    let id = op.get("operationId").and_then(Value::as_str).map(str::to_string).unwrap_or_else(|| format!("{method}{path}"));
    let (name, cap) = (ident(&id), format!("{adapter}_{}", ident(&id)));
    let class = if matches!(method, "get" | "head") || crate::brk!("openapi_does_get" => true; false) { "reads" } else { "does" };
    let said = op.get("summary").and_then(Value::as_str).unwrap_or("");
    let verb = method.to_uppercase();
    let mut out = format!("-- operation {id}: {verb} {path}: {said}\ncapability({cap}, {adapter}, {class}).\nhttp_op({cap}, {}, {}).\n", quote(&verb), quote(path));
    let mut params: Vec<&Value> = op.get("parameters").and_then(Value::as_array).into_iter().flatten().map(|p| resolve(doc, p)).collect();
    for p in shared.iter().map(|p| resolve(doc, p)) {
        if !params.iter().any(|q| q.get("name") == p.get("name") && q.get("in") == p.get("in")) {
            params.push(p);
        }
    }
    let mut pos = 0;
    for p in params {
        let (Some(n), Some(at)) = (p.get("name").and_then(Value::as_str), p.get("in").and_then(Value::as_str)) else { continue };
        if at == "cookie" {
            continue;
        }
        pos += 1;
        out.push_str(&format!("arg({cap}, {pos}, {}, {}).\nhttp_in({cap}, {pos}, {at}, {}).\n", ident(n), ty(doc, p.get("schema").unwrap_or(&Value::Null)), quote(n)));
    }
    let body = op.pointer("/requestBody/content/application~1json/schema").map(|s| resolve(doc, s));
    for (n, s) in body.and_then(|b| b.get("properties")).and_then(Value::as_object).into_iter().flatten() {
        pos += 1;
        out.push_str(&format!("arg({cap}, {pos}, {}, {}).\nhttp_in({cap}, {pos}, body, {}).\n", ident(n), ty(doc, s), quote(n)));
    }
    let needs = op.get("security").or_else(|| doc.get("security")).and_then(Value::as_array).and_then(|a| a.first()).and_then(Value::as_object);
    for n in needs.into_iter().flat_map(|o| o.keys()) {
        out.push_str(&format!("http_needs({cap}, {}).\n", ident(n)));
    }
    let answer = op.get("responses").and_then(Value::as_object).and_then(|r| {
        let mut ok: Vec<(&String, &Value)> = r.iter().filter(|(c, _)| c.starts_with('2')).collect();
        ok.sort_by_key(|x| x.0);
        ok.into_iter().find_map(|(_, v)| resolve(doc, v).pointer("/content/application~1json/schema"))
    }).map(|s| resolve(doc, s));
    let row = answer.map(|s| if s.get("type").and_then(Value::as_str) == Some("array") { resolve(doc, s.get("items").unwrap_or(&Value::Null)) } else { s });
    match row.and_then(|r| r.get("properties")).and_then(Value::as_object).filter(|p| !p.is_empty()) {
        Some(props) => {
            out.push_str(&format!("answers({cap}, {name}, {}).\n", props.len() + 1));
            for (i, f) in props.keys().enumerate() {
                out.push_str(&format!("http_field({cap}, {}, {}).\n", i + 2, quote(f)));
            }
        }
        None => out.push_str(&format!("answers({cap}, http_body, 2).\n")),
    }
    (cap, out)
}

/// Where an operation sends: its method and path template, each argument's place and name on the wire, and the
/// credentials `(how, name, key)` it carries.
#[derive(Clone)]
pub(crate) struct Op {
    pub method: String,
    pub path: String,
    pub places: Vec<(String, String)>,
    pub auth: Vec<(String, String, String)>,
}

/// One batch of the `openapi` kind: each want `(key, arguments by wire name, idempotency key)` one request to `base`,
/// answered in the text an exec program prints.
pub(crate) fn call(base: &str, op: &Op, rel: &str, fields: &[String], wants: &[(String, Value, Option<String>)]) -> Result<String, String> {
    let mut out = String::new();
    for (key, args, idem) in wants {
        let arg = |n: &str| args.get(n).map(|v| v.as_str().map_or_else(|| v.to_string(), str::to_string));
        let mut path = op.path.clone();
        let (mut query, mut headers, mut body) = (Vec::new(), Vec::new(), serde_json::Map::new());
        for (at, n) in &op.places {
            let Some(v) = arg(n) else { continue };
            match at.as_str() {
                "path" => path = path.replace(&format!("{{{n}}}"), &crate::net::escape(&v)),
                "query" => query.push(format!("{}={}", crate::net::escape(n), crate::net::escape(&v))),
                "header" => headers.push((n.as_str(), v)),
                _ => {
                    body.insert(n.clone(), args[n.as_str()].clone());
                }
            }
        }
        if let Some(i) = idem {
            headers.push(("idempotency-key", i.clone()));
        }
        let mut owned = Vec::new();
        for (how, n, v) in &op.auth {
            let (h, q) = crate::net::credential(how, n, v);
            owned.extend(h);
            query.extend(q);
        }
        headers.extend(owned.iter().map(|(k, v)| (k.as_str(), v.clone())));
        let url = format!("{}{path}{}{}", base.trim_end_matches('/'), if query.is_empty() { "" } else { "?" }, query.join("&"));
        let sent = (!body.is_empty()).then(|| Value::Object(body));
        let r = match crate::net::send(&op.method, &url, &headers, sent.as_ref()) {
            Ok(r) => r,
            Err(e) => {
                let e = op.auth.iter().fold(e, |e, (_, _, v)| e.replace(&crate::net::escape(v), "***").replace(v.as_str(), "***"));
                out.push_str(&format!("failed({key}, {}).\n", quote(&e)));
                continue;
            }
        };
        if r.status / 100 != 2 {
            let said: String = r.body.chars().take(200).collect();
            out.push_str(&format!("failed({key}, {}).\n", quote(&format!("HTTP {}: {said}", r.status))));
            continue;
        }
        if fields.is_empty() {
            out.push_str(&format!("http_body({key}, {}).\n", quote(&r.body)));
            continue;
        }
        let rows = match serde_json::from_str::<Value>(&r.body) {
            Ok(Value::Array(a)) => a,
            Ok(o @ Value::Object(_)) => vec![o],
            _ => {
                out.push_str(&format!("failed({key}, \"the answer is not a JSON object or array\").\n"));
                continue;
            }
        };
        for o in &rows {
            let cols: Vec<String> = fields.iter().map(|f| fact_value(o.get(f).unwrap_or(&Value::Null))).collect();
            out.push_str(&format!("{rel}({key}, {}).\n", cols.join(", ")));
        }
        if rows.is_empty() {
            out.push_str(&format!("answered({key}).\n"));
        }
    }
    Ok(out)
}
